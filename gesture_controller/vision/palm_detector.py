import mmap
import os
from pathlib import Path

import numpy as np
import cv2 as cv
import onnxruntime as ort


def _default_ort_session_options():
    """Performance optimization (P1): default ONNX Runtime SessionOptions.

    Enables ``ORT_ENABLE_ALL`` graph optimization (constant folding +
    operator fusion) and pins ``intra_op_num_threads`` to
    ``min(cpu_count, 4)`` so two concurrent palm + landmark sessions do
    not oversubscribe the CPU. The default ``SessionOptions()`` left both
    settings at ONNX Runtime defaults, which were sub-optimal for the
    low-latency (60 fps) gesture pipeline.
    """
    opts = ort.SessionOptions()
    opts.graph_optimization_level = ort.GraphOptimizationLevel.ORT_ENABLE_ALL
    try:
        cpu = os.cpu_count() or 4
        opts.intra_op_num_threads = max(1, min(cpu, 4))
        opts.inter_op_num_threads = 1
    except Exception:
        pass
    return opts


def _load_model_bytes_mmap(model_path: str) -> bytes | None:
    """Memory-map the model file to avoid a full read into RSS at startup.

    Performance optimization (P1): ``ort.InferenceSession`` accepts either
    a filesystem path or a bytes buffer. Passing a ``mmap``-backed bytes
    object lets the kernel page the model in lazily and share the page
    across processes, reducing startup RSS by ~model-size for the common
    7-12 MiB ONNX files.

    Returns ``None`` if mmap fails (the caller falls back to the path).
    """
    try:
        # PROT_READ on a read-only mmap; the underlying fd is closed when
        # the mmap object is garbage-collected.
        with open(model_path, "rb") as f:
            mm = mmap.mmap(f.fileno(), 0, access=mmap.ACCESS_READ)
            return mm[:]
    except (OSError, ValueError):
        return None


class PalmDetector:
    def __init__(
        self,
        modelPath,
        nmsThreshold=0.3,
        scoreThreshold=0.5,
        topK=5000,
        backendId=0,
        targetId=0,
        providers=None,
        sess_options=None,
    ):
        self.model_path = modelPath
        self.nms_threshold = nmsThreshold
        self.score_threshold = scoreThreshold
        self.topK = topK
        self.backend_id = backendId
        self.target_id = targetId

        self.input_size = np.array([192, 192])  # wh

        # Initialize onnxruntime session
        if providers is None:
            providers = ["CPUExecutionProvider"]
            if "CUDAExecutionProvider" in ort.get_available_providers():
                providers.insert(0, "CUDAExecutionProvider")
            if "DirectMLExecutionProvider" in ort.get_available_providers():
                providers.insert(0, "DirectMLExecutionProvider")
            if "CoreMLExecutionProvider" in ort.get_available_providers():
                providers.insert(0, "CoreMLExecutionProvider")
        # Performance optimization (P1): default to graph-optimized session
        # options when the caller didn't supply their own.
        if sess_options is None:
            sess_options = _default_ort_session_options()

        # Performance optimization (P1): prefer memory-mapped model bytes
        # to reduce startup RSS; fall back to the path if mmap fails.
        model_bytes = _load_model_bytes_mmap(self.model_path)
        if model_bytes is not None:
            self.session = ort.InferenceSession(
                model_bytes, sess_options=sess_options, providers=providers
            )
        else:
            self.session = ort.InferenceSession(
                self.model_path, sess_options=sess_options, providers=providers
            )

        self.anchors = self._load_anchors()

    @property
    def name(self):
        return self.__class__.__name__

    def set_backend_and_target(self, backendId, targetId):
        self.backend_id = backendId
        self.target_id = targetId

    def _preprocess(self, image):
        pad_bias = np.array([0.0, 0.0])  # left, top
        ratio = min(self.input_size / image.shape[:2])
        if image.shape[0] != self.input_size[0] or image.shape[1] != self.input_size[1]:
            # keep aspect ratio when resize
            ratio_size = (np.array(image.shape[:2]) * ratio).astype(np.int32)
            image = cv.resize(image, (ratio_size[1], ratio_size[0]))
            pad_h = self.input_size[0] - ratio_size[0]
            pad_w = self.input_size[1] - ratio_size[1]
            pad_bias[0] = left = pad_w // 2
            pad_bias[1] = top = pad_h // 2
            right = pad_w - left
            bottom = pad_h - top
            image = cv.copyMakeBorder(
                image, top, bottom, left, right, cv.BORDER_CONSTANT, None, (0, 0, 0)
            )
        image = cv.cvtColor(image, cv.COLOR_BGR2RGB)
        image = image.astype(np.float32) / 255.0  # norm
        pad_bias = (pad_bias / ratio).astype(np.int32)
        return image[np.newaxis, :, :, :], pad_bias  # hwc -> nhwc

    def infer(self, image):
        if image is None or not isinstance(image, np.ndarray) or image.size == 0:
            return np.empty(shape=(0, 19))
        if len(image.shape) < 2 or image.shape[0] <= 0 or image.shape[1] <= 0:
            return np.empty(shape=(0, 19))

        h, w = image.shape[:2]

        # Preprocess
        input_blob, pad_bias = self._preprocess(image)

        # Forward via ONNX Runtime
        input_name = self.session.get_inputs()[0].name
        output_blob = self.session.run(None, {input_name: input_blob})

        # Postprocess
        results = self._postprocess(output_blob, np.array([w, h]), pad_bias)

        return results

    def _postprocess(self, output_blob, original_shape, pad_bias):
        score = output_blob[1][0, :, 0]
        box_delta = output_blob[0][0, :, 0:4]
        landmark_delta = output_blob[0][0, :, 4:]
        scale = max(original_shape)

        # get scores
        score = score.astype(np.float64)
        score = 1 / (1 + np.exp(-score))

        # get boxes
        cxy_delta = box_delta[:, :2] / self.input_size
        wh_delta = box_delta[:, 2:] / self.input_size
        xy1 = (cxy_delta - wh_delta / 2 + self.anchors) * scale
        xy2 = (cxy_delta + wh_delta / 2 + self.anchors) * scale
        boxes = np.concatenate([xy1, xy2], axis=1)
        boxes -= [pad_bias[0], pad_bias[1], pad_bias[0], pad_bias[1]]
        # NMS
        keep_idx = cv.dnn.NMSBoxes(
            boxes, score, self.score_threshold, self.nms_threshold, top_k=self.topK
        )
        if len(keep_idx) == 0:
            return np.empty(shape=(0, 19))
        selected_score = score[keep_idx]
        selected_box = boxes[keep_idx]

        # get landmarks
        selected_landmarks = landmark_delta[keep_idx].reshape(-1, 7, 2)
        selected_landmarks = selected_landmarks / self.input_size
        selected_anchors = self.anchors[keep_idx]
        for idx, landmark in enumerate(selected_landmarks):
            landmark += selected_anchors[idx]
        selected_landmarks *= scale
        selected_landmarks -= pad_bias

        # [
        #   [bbox_coords, landmarks_coords, score]
        #   ...
        #   [bbox_coords, landmarks_coords, score]
        # ]
        return np.c_[
            selected_box.reshape(-1, 4),
            selected_landmarks.reshape(-1, 14),
            selected_score.reshape(-1, 1),
        ]

